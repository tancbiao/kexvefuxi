function getKeji2026Equip(studentName) {
    if (!studentName) return null;
    return KEJI2026_EXCLUSIVE_EQUIPS.find(e => e.studentName === studentName) || null;
}

function getKeji2026EquipById(studentId) {
    if (!studentId) return null;
    return KEJI2026_EXCLUSIVE_EQUIPS.find(e => e.studentId === studentId) || null;
}

/**
 * 自动发放2026科技节专属神话装备
 * 在collectPendingRewards之后调用
 */
function grantKeji2026Equip() {
    try {
        if (!gameState || gameState.isGuest) return;
        if (typeof KEJI2026_EXCLUSIVE_EQUIPS === 'undefined') return;
        
        var studentName = gameState.studentName;
        var studentId = gameState.studentId;
        var equip = getKeji2026Equip(studentName) || getKeji2026EquipById(studentId);
        if (!equip) return;
        
        // v713修复: 改用尝试次数计数器（最多50次），解决"领了没保存到就没了"的问题
        // 清理旧版一次性标记，迁移到新计数器机制
        var oldGrantKey = 'keji2026_granted_' + (studentId || studentName);
        if (localStorage.getItem(oldGrantKey)) { localStorage.removeItem(oldGrantKey); }
        
        var attemptKey = 'keji2026_attempt_' + (studentId || studentName);
        var attempts = parseInt(localStorage.getItem(attemptKey) || '0');
        
        // 检查背包是否已有此装备（兼容null填充数组和普通数组）
        if (gameState.equipment && Array.isArray(gameState.equipment)) {
            var hasEquip = gameState.equipment.some(function(e) {
                return e && e.id === equip.id;
            });
            if (hasEquip) {
                // 装备已在背包中，标记完成
                localStorage.setItem(attemptKey, '50');
                return;
            }
        }
        
        // 超过50次尝试仍未成功，不再发放
        if (attempts >= 50) return;
        
        // 递增尝试次数
        localStorage.setItem(attemptKey, String(attempts + 1));
        
        // 初始化装备数组（适配500格上限）
        if (!gameState.equipment) gameState.equipment = [];
        if (!Array.isArray(gameState.equipment)) gameState.equipment = [];
        
        // 清理null占位
        gameState.equipment = gameState.equipment.filter(function(e) { return e !== null; });
        
        // 添加装备（深拷贝防止引用污染）
        var equipCopy = JSON.parse(JSON.stringify(equip));
        equipCopy.obtainedAt = Date.now();
        equipCopy.source = '2026科技节专属';
        // 兼容游戏背包字段名（背包渲染用 pointBonus/effect/affixDetails）
        equipCopy.pointBonus = equipCopy.multiplier || 3.0;
        equipCopy.effect = equipCopy.desc || '';
        if (equipCopy.affixes && Array.isArray(equipCopy.affixes)) {
            equipCopy.affixDetails = equipCopy.affixes.map(function(a) {
                return { name: a.name, value: a.effect, unit: '' };
            });
        }
        gameState.equipment.push(equipCopy);
        
        // 保存数据（v713: 不再设置一次性标记，改用计数器机制，失败可重试）
        if (typeof saveUserData === 'function') {
            saveUserData();
        }
        
        // 显示通知
        if (typeof showAchievementUnlock === 'function') {
            showAchievementUnlock({
                name: '🎖️ 科技节专属装备',
                icon: '🏆',
                description: equip.name
            });
        }
        
        console.log('[科技节装备] 已发放给 ' + studentName + ': ' + equip.name);
    } catch(e) {
        console.error('[科技节装备] 发放失败:', e);
    }
}

